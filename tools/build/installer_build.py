def find_iscc() -> str:
    found = shutil.which('ISCC.exe') or shutil.which('iscc')
    if found:
        return str(Path(found).resolve())
    roots = [os.environ.get('ProgramFiles', r'C:\Program Files'),
             os.environ.get('ProgramFiles(x86)', r'C:\Program Files (x86)'),
             str(Path(os.environ.get('LOCALAPPDATA', str(Path.home()))) / 'Programs')]
    for root in roots:
        for name in ('Inno Setup 7', 'Inno Setup 6'):
            candidate = Path(root) / name / 'ISCC.exe'
            if candidate.is_file():
                return str(candidate.resolve())
    return ''


def inspect_iscc(value: str) -> Path:
    path = Path(value or find_iscc()).expanduser().resolve()
    if not path.is_file() or path.name.lower() != 'iscc.exe':
        raise BuildError('설치 EXE를 만들려면 Inno Setup 6.4 이상 또는 7의 ISCC.exe를 선택하세요. 설치 안내 버튼에서 받을 수 있습니다.')
    if not (path.parent / 'Languages' / 'Korean.isl').is_file():
        raise BuildError('Inno Setup의 Languages/Korean.isl이 없습니다. 정상 설치한 Inno Setup을 선택하세요.')
    if pe_machine(path) not in (0x14c, 0x8664):
        raise BuildError('Windows용 Inno Setup 컴파일러가 아닙니다.')
    return path


def iss_string(value) -> str:
    text = str(value)
    if any(x in text for x in ('\r', '\n', '\x00', '"')):
        raise BuildError('설치 스크립트 경로에 사용할 수 없는 문자가 있습니다.')
    return text.replace('{', '{{')



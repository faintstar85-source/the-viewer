def build_installer(runner, product: Path, icon: Path, version: str, compiler: Path, repo: str) -> dict:
    compiler = inspect_iscc(str(compiler))
    record = write_installer_script(product, icon, version, runner.run / 'Installer', repo)
    target = Path(record['output'])
    if target.exists():
        raise BuildError('이번 작업의 설치 출력 파일이 이미 있습니다. 새 빌드 작업을 시작하세요.')
    runner.command([str(compiler), '/Qp', record['script']], label='inno_setup', timeout=3600)
    runner.check()
    if not target.is_file() or pe_machine(target) not in (0x14c, 0x8664):
        raise BuildError('Inno Setup이 성공했지만 설치 실행파일이 없습니다.')
    record.update(path=str(target), bytes=target.stat().st_size, sha256=sha256(target, runner.check),
                  compiler=str(compiler), compiled=True, installed_on_clean_windows_tested=False)
    atomic_json(target.parent / 'Installer_Record.json', record)
    return record
